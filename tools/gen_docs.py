"""Write the docs text whose facts live in code, so the docs quote the code instead of restating it.

python tools/gen_docs.py            # rewrite every generated block and page
python tools/gen_docs.py --check    # exit 1 if any differs from what the code says (CI)

Generated blocks sit between ``<!-- BEGIN generated: NAME -->`` and ``<!-- END generated: NAME -->`` in any
file listed in `BLOCKS`; generated pages are whole files (`PAGES`).

- block ``support-matrix`` (docs/formats.md): card x format. The row labels are written here
  (`CARDS`, each naming a card a target table knows); every cell is read through the same `Target.plan` a
  build calls, and a refusal is quoted as the build prints it. A planned row whose table has not observed it on
  a card stops the generator: the table lists only bindings a card has run.
- page docs/cli.md: the ``--help`` of every command of ``qda``, ``qda-kl`` and ``qda-agent``.

Apart from the row labels, nothing generated is written by hand; edit the code (a table's rows or aliases, a
parser's help) instead.
"""

from __future__ import annotations

import argparse
import contextlib
import io
import os
import sys
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for _pkg in ("qda-quant", "qda-kl", "qda-agent"):
    sys.path.insert(0, str(ROOT / "packages" / _pkg / "src"))

#: argparse wraps --help to the terminal; `cli_reference` fixes the width so every machine writes the same page.
HELP_COLUMNS = "100"
HEADER = "<!-- generated by tools/gen_docs.py from {src}; do not edit by hand -->\n"
#: The note at the top of every generated block.
BLOCK_NOTE = "<!-- generated by tools/gen_docs.py; edit the code, not this block -->\n"


# ---------------------------------------------------------------- support matrix


#: The rows: cards a user knows, each with one of its names in a target table (`Table.aliases`) or in
#: `target._PENDING`. Only the label is written here; what each card runs comes from its table.
CARDS = (
    ("H100 / H200 / H800", "h100"),
    ("A100", "a100"),
    ("L40S", "l40s"),
    ("RTX PRO 6000", "rtx6000"),
    ("B200", "b200"),
    ("GB300", "gb300"),
)


#: Column order only; the set of columns is `qda_quant.format.PRESETS` (checked in `support_matrix`).
FORMAT_ORDER = ("w4a16", "w3a16", "w4a8", "w4a4")


#: Layer kinds a cell reports; a cell names both when they differ.
KINDS = ("dense", "moe")
#: What a refused cell of a format needs, in the cell itself (the refusal text names kernels and arch numbers).
NEEDS = {"w4a8": "Hopper only", "w4a4": "Blackwell only"}


def _cell(target, fmt) -> tuple[str, str | None]:
    """One cell for (card, format): a mark per layer kind (one mark when both agree), and the refusal reason, in
    the target table's own words, read through the `Target.plan` a build calls.

    A cell is ✅ only for a row a card has run. A planned row that still carries the table's unverified note stops
    the generator: the matrix lists what has been observed, so a new row is added to its table's `observed` set
    once a card has served it, or it is refused with the reason.
    """
    from qda_quant.step import Refused

    marks, why = {}, None
    for kind in KINDS:
        try:
            p = target.plan(fmt, kind)
        except Refused as e:
            marks[kind] = "❌"
            why = why or str(e).split(": ", 1)[-1]  # drop the "<format> <kind> on <arch> vLLM <ver>" prefix
            continue
        note = next((n for n in p.notes if "unverified" in n), None)
        if note is not None:
            raise SystemExit(
                f"tools/gen_docs.py: {target.arch} {fmt.name} {kind} is not observed on a card ({note!r}); "
                "add the row to the table's `observed` set or make its `rows` refuse it"
            )
        marks[kind] = "✅"
    if len(set(marks.values())) == 1:
        return marks["dense"], why
    return " · ".join(f"{m} {k}" for k, m in marks.items()), why


def support_matrix() -> str:
    """Which format each card serves, from the target tables a build plans with; then the cards DeepSeek V4.1
    serves on and its refusal on an RTX PRO 6000, read through the `prefill_for` a V4.1 build calls."""
    from qda_quant import target as t
    from qda_quant.arch.adapters.deepseek_v41.prefill import prefill_for as v41_prefill
    from qda_quant.format import PRESETS
    from qda_quant.step import Refused

    if set(FORMAT_ORDER) != set(PRESETS):
        raise SystemExit(
            f"tools/gen_docs.py: FORMAT_ORDER {FORMAT_ORDER} != the formats in PRESETS {tuple(PRESETS)}"
        )
    lines = [
        "Find the card you will **serve** on. A checkpoint can be built on any card for another one "
        "(`--set target=h100`).\n",
        "✅ observed on a card · ❌ refused. Where dense and MoE layers differ, the cell names both.\n",
        "| GPU | " + " | ".join(fmt.upper() for fmt in FORMAT_ORDER) + " |",
        "|---|" + "---|" * len(PRESETS),
    ]
    w4a8_why, v41_cards, v41_why = None, [], {}
    for label, name in CARDS:
        try:
            target = t.Target.parse(name)
        except Refused:
            if name not in t._PENDING:
                raise
            cells = ["❌ no table for this card yet (see install)"] * len(PRESETS)
        else:
            try:
                v41_prefill(target)
                v41_cards.append(label)
            except Refused as e:
                v41_why[label] = str(e)
            cells = []
            for fmt in FORMAT_ORDER:
                mark, why = _cell(target, PRESETS[fmt])
                if why is not None and fmt == "w4a8":
                    w4a8_why = why
                if why is not None and fmt in NEEDS:
                    mark = f"{mark} {NEEDS[fmt]}"
                cells.append(mark)
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "On a card marked ❌, build `w4a16` or `w3a16`: every card above serves both."
        + (f' A `w4a8` build on one of them stops with: "{w4a8_why}".' if w4a8_why else ""),
        "",
        f"DeepSeek V4.1 is served on {' and '.join(v41_cards)} only. A V4.1 build for an RTX PRO 6000 stops "
        f'with: "{v41_why["RTX PRO 6000"]}".',
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- CLI reference


def _help(main: Callable[[list[str]], object], argv: list[str]) -> str:
    """The text ``main(argv + ["--help"])`` prints."""
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.suppress(SystemExit):
        main([*argv, "--help"])
    return out.getvalue()


def _parser(main: Callable[[list[str]], object]) -> argparse.ArgumentParser:
    """The parser ``main`` builds, caught at its ``parse_args`` (before it runs anything)."""
    caught: list[argparse.ArgumentParser] = []

    def grab(parser: argparse.ArgumentParser, *_: object, **__: object) -> None:
        caught.append(parser)
        raise SystemExit(0)

    real = argparse.ArgumentParser.parse_args
    argparse.ArgumentParser.parse_args = grab  # type: ignore[method-assign]
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.suppress(SystemExit):
            main([])
    finally:
        argparse.ArgumentParser.parse_args = real  # type: ignore[method-assign]
    return caught[0]


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    """A parser's subcommands, by name, in the order it lists them (none when it has no subparsers).

    Read from the parser's own subparsers action, not from the ``{a,b}`` of its usage line, which also
    spells an option's choices (``--format {md,html}``).
    """
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            names = getattr(action, "public", tuple(action.choices))
            return {name: action.choices[name] for name in names}
    return {}


def _commands(
    main: Callable[[list[str]], object],
    prog: str,
    argv: list[str],
    parser: argparse.ArgumentParser,
    depth: int,
) -> list[str]:
    """Markdown for one command's --help, then each of its subcommands', depth first."""
    text = _help(main, argv)
    level = "#" * min(2 + len(argv), 4)
    lines = [f"{level} `{' '.join([prog, *argv])}`\n", "```text", text.rstrip(), "```\n"]
    if depth:
        for name, sub in _subcommands(parser).items():
            lines += _commands(main, prog, [*argv, name], sub, depth - 1)
    return lines


def _stability() -> str:
    """What 0.1.x keeps stable on the CLI page; output and messages are not part of it."""
    from qda_agent.cli import PUBLIC as agent
    from qda_kl.cli import PUBLIC as kl
    from qda_quant.cli import PUBLIC as quant

    named = "; ".join(
        f"`{prog}` {', '.join(f'`{c}`' for c in cmds)}"
        for prog, cmds in (("qda", quant), ("qda-kl", kl), ("qda-agent", agent))
    )
    return (
        f"**Stability.** For scripts that call these commands ({named}): in 0.1.x each command and its flags "
        "keep their name and meaning. Changing one takes a new minor version and is listed in "
        "[CHANGELOG.md](https://github.com/humanfia/qda/blob/main/CHANGELOG.md). Output text and messages may "
        "change.\n"
    )


def cli_reference() -> str:
    """Every command's --help: each program, then its subcommands and theirs, in the order the parser lists them."""
    from qda_agent.cli import main as agent
    from qda_kl.cli import main as kl
    from qda_quant.cli import main as quant

    lines = [
        HEADER.format(src="each command's --help"),
        "# CLI reference\n",
        "Every command's `--help`, as printed. `qda` builds and inspects checkpoints, `qda-kl` scores them against "
        "the original model, `qda-agent` runs the search (`prepare`, `search`, `status`).\n",
        _stability(),
    ]
    saved = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = HELP_COLUMNS
    try:
        for prog, main in (("qda", quant), ("qda-kl", kl), ("qda-agent", agent)):
            lines += _commands(main, prog, [], _parser(main), depth=2)
    finally:
        if saved is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = saved
    return "\n".join(lines)


#: Whole generated pages.
PAGES: dict[str, Callable[[], str]] = {"docs/cli.md": cli_reference}
#: Generated blocks: name -> (text, the files that hold the block).
BLOCKS: dict[str, tuple[Callable[[], str], tuple[str, ...]]] = {
    "support-matrix": (support_matrix, ("docs/formats.md",)),
}


def _with_block(text: str, name: str, body: str, rel: str) -> str:
    """`text` with the block `name` replaced by `body`."""
    begin, end = f"<!-- BEGIN generated: {name} -->", f"<!-- END generated: {name} -->"
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < i:
        raise SystemExit(f"{rel}: no {begin} ... {end} block")
    return f"{text[:i]}{begin}\n{BLOCK_NOTE}\n{body.strip()}\n\n{text[j:]}"


def expected() -> dict[str, str]:
    """Every generated file's full text, by path relative to the repository root."""
    out = {rel: make() for rel, make in PAGES.items()}
    for name, (make, files) in BLOCKS.items():
        body = make()
        for rel in files:
            text = out.get(rel) or (ROOT / rel).read_text()
            out[rel] = _with_block(text, name, body, rel)
    return out


def main(argv: list[str] | None = None) -> int:
    """Write the generated text, or with --check report which files are stale."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a file differs from what the code says")
    a = ap.parse_args(argv)
    stale = []
    for rel, text in expected().items():
        path = ROOT / rel
        if path.is_file() and path.read_text() == text:
            continue
        if a.check:
            stale.append(rel)
        else:
            path.write_text(text)
            print(f"wrote {rel}")
    if stale:
        print(f"stale generated docs: {', '.join(stale)}; run python tools/gen_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
